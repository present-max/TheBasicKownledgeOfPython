#字符串的定义
s1="hello"
s2='world'
#定义多行字符串
s3="""hello
world
!"""
print(s1)
print(s2)
print(s3)
#字符串的拼接
str1="我今年"
num=19
str2="岁"
#字符串不能与其它类型拼接，必须将其它类型转成str
print(str1+str(num)+str2)
#字符串的格式化
#方式一
print("我今年%s岁"%num)
#方式二
print(f"我今年{num}岁")

#字符串索引
print(s1[0])
#字符串切片
print(s1[1:3])
#字符串不可变，不能修改字符串中的元素
